import { describe, expect, it } from "vitest";
import {
    entrySubpaths,
    exportTarget,
    formatBytes,
    formatReport,
    GZIP_TOLERANCE,
    isPackageOrSubpath,
    type PackageSizes,
    REPORT,
    sizeOptions,
    specifierOf,
    staleProblem,
} from "../../scripts/size-report.ts";

// `pnpm size` bundles every entry from the built packages: these pin what it writes to
// docs/size.md and how `--check` compares it.

const PACKAGES: PackageSizes[] = [
    {
        name: "@fragiola/primitives",
        peers: [],
        entries: [
            { specifier: "@fragiola/primitives/id", minified: 81, gzip: 98 },
        ],
    },
    {
        name: "@fragiola/primitives-react",
        peers: ["react", "react-dom"],
        entries: [
            {
                specifier: "@fragiola/primitives-react/dialog",
                minified: 9059,
                gzip: 3558,
                withoutToolkit: { minified: 5364, gzip: 2207 },
            },
        ],
    },
];

describe("formatReport", () => {
    const report = formatReport(PACKAGES, "rolldown 1.3.2");

    it("starts with a header saying it is generated and how", () => {
        expect(report.startsWith("<!-- Generated by `pnpm size`")).toBe(true);
        expect(report).toContain("# Bundle size");
        expect(report).toContain("rolldown 1.3.2");
        expect(report).toContain("`pnpm size --check`");
    });

    it("writes a table per package, the toolkit-external columns for framework entries", () => {
        expect(report).toContain(
            "## @fragiola/primitives\n\nNo peers: everything is bundled.\n\n| entry | min | min + gzip |\n| --- | ---: | ---: |\n| `@fragiola/primitives/id` | 81 B | 98 B |",
        );
        expect(report).toContain("External: `react`, `react-dom`.");
        expect(report).toContain(
            "| `@fragiola/primitives-react/dialog` | 9,059 B | 3,558 B | 5,364 B | 2,207 B |",
        );
        expect(report.endsWith("|\n")).toBe(true);
    });

    it("is the same for the same sizes", () => {
        expect(formatReport(PACKAGES, "rolldown 1.3.2")).toBe(report);
    });
});

describe("formatBytes", () => {
    it("groups thousands without a locale", () => {
        expect(formatBytes(0)).toBe("0 B");
        expect(formatBytes(999)).toBe("999 B");
        expect(formatBytes(1000)).toBe("1,000 B");
        expect(formatBytes(1234567)).toBe("1,234,567 B");
    });
});

describe("staleProblem", () => {
    it("is nothing for an up-to-date report", () => {
        expect(staleProblem("a\n", "a\n")).toBeUndefined();
    });

    it("says the report is missing or stale", () => {
        expect(staleProblem(undefined, "a\n")).toMatch(
            `${REPORT} does not exist`,
        );
        expect(staleProblem("b\n", "a\n")).toMatch(`${REPORT} is stale`);
    });
});

// Epic #22 (#21): the gzip sizes come from Node's zlib, which is not pinned.
describe("staleProblem across zlib versions", () => {
    const report = (gzip: number, minified = 4000) =>
        [
            "# Bundle size",
            "",
            "| entry | min | min + gzip | min, toolkit external | min + gzip, toolkit external |",
            "| --- | ---: | ---: | ---: | ---: |",
            `| \`@x/dialog\` | ${formatBytes(minified)} | ${formatBytes(gzip)} | 2,000 B | 900 B |`,
            "",
        ].join("\n");

    it("accepts gzip sizes a few bytes apart (another zlib)", () => {
        expect(staleProblem(report(1200), report(1209))).toBeUndefined();
        expect(staleProblem(report(1200), report(1184))).toBeUndefined();
    });

    it("still fails a gzip size past the tolerance", () => {
        const far = Math.ceil(1200 * GZIP_TOLERANCE.ratio) + 1;
        expect(staleProblem(report(1200), report(1200 + far))).toMatch(
            "is stale",
        );
    });

    it("fails any change of a minified size, the code's own measure", () => {
        expect(staleProblem(report(1200, 4000), report(1200, 4001))).toMatch(
            "is stale",
        );
    });

    it("fails a change outside the tables", () => {
        expect(
            staleProblem(report(1200), report(1200).replace("Bundle", "Size")),
        ).toMatch("is stale");
    });
});

describe("sizeOptions", () => {
    it("reads --check and rejects anything else", () => {
        expect(sizeOptions([])).toEqual({ check: false });
        expect(sizeOptions(["--check"])).toEqual({ check: true });
        expect(() => sizeOptions(["--write"])).toThrow(
            "unknown argument: --write",
        );
    });
});

describe("entries", () => {
    const exports = {
        ".": {
            "@fragiola/source": "./src/index.ts",
            types: "./dist/index.d.ts",
            import: "./dist/index.js",
            default: "./dist/index.js",
        },
        "./dialog": {
            types: "./dist/types/dialog.d.ts",
            default: "./dist/fesm2022/dialog.mjs",
        },
        "./package.json": "./package.json",
    };

    it("lists every subpath but ./package.json, in order", () => {
        expect(entrySubpaths(exports)).toEqual([".", "./dialog"]);
    });

    it("bundles an entry from its import target, else its default", () => {
        expect(exportTarget(exports, ".")).toBe("./dist/index.js");
        expect(exportTarget(exports, "./dialog")).toBe(
            "./dist/fesm2022/dialog.mjs",
        );
        expect(exportTarget(exports, "./tabs")).toBeUndefined();
    });

    it("names an entry by its specifier", () => {
        expect(specifierOf("@fragiola/primitives", ".")).toBe(
            "@fragiola/primitives",
        );
        expect(specifierOf("@fragiola/primitives", "./scroll-lock")).toBe(
            "@fragiola/primitives/scroll-lock",
        );
    });

    it("keeps a peer's subpaths external, never a longer name", () => {
        expect(isPackageOrSubpath("react/jsx-runtime", "react")).toBe(true);
        expect(isPackageOrSubpath("react-dom", "react")).toBe(false);
        expect(
            isPackageOrSubpath(
                "@fragiola/primitives-react",
                "@fragiola/primitives",
            ),
        ).toBe(false);
    });
});
